#!/usr/bin/env node
'use strict';

const { spawn } = require('child_process');
const fs = require('fs');
const http = require('http');
const net = require('net');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');

const INSTANCE_DEFINITIONS = [
    { id: 'simulation-1', label: 'Simulation 1', managementPort: 8181, authPort: 2111, gamePort: 7781 },
    { id: 'simulation-2', label: 'Simulation 2', managementPort: 8182, authPort: 2112, gamePort: 7782 },
    { id: 'simulation-3', label: 'Simulation 3', managementPort: 8183, authPort: 2113, gamePort: 7783 }
];

function toIniPath(filePath) {
    return path.relative(rootDir, filePath).replace(/\\/g, '/');
}

function instanceFiles(definition, baseDir = rootDir) {
    const runtimeDir = path.join(baseDir, 'tmp', 'simulations', definition.id);
    const databasePath = path.join(runtimeDir, 'nodel2.sqlite');
    const historyPath = path.join(runtimeDir, 'nodel2.history.sqlite');
    const configPath = path.join(runtimeDir, 'config.ini');
    const launcherSettingsPath = path.join(runtimeDir, 'launcher-settings.json');
    return { runtimeDir, databasePath, historyPath, configPath, launcherSettingsPath };
}

function configText(definition, files) {
    return [
        '; Generated by scripts/run-simulations.js. Edit only if you need a custom instance.',
        '[Database]',
        `path = ${toIniPath(files.databasePath)}`,
        `historyPath = ${toIniPath(files.historyPath)}`,
        '',
        '[AuthServer]',
        `port = ${definition.authPort}`,
        '',
        '[GameServer]',
        `port = ${definition.gamePort}`,
        '',
        '[WorldObserver]',
        'enabled = true',
        'hostname = 127.0.0.1',
        `port = ${definition.managementPort}`,
        ''
    ].join('\n');
}

function ensureInstanceFiles(definition, baseDir = rootDir) {
    const files = instanceFiles(definition, baseDir);
    fs.mkdirSync(files.runtimeDir, { recursive: true });
    if (!fs.existsSync(files.configPath)) {
        fs.writeFileSync(files.configPath, configText(definition, files), 'utf8');
    }
    return files;
}

function managementUrl(definition) {
    return `http://127.0.0.1:${definition.managementPort}/observer/settings/server`;
}

function environmentFor(definition, files, { noBrowser = false } = {}) {
    const environment = {
        ...process.env,
        L2NODE_SHARED_CONFIG_FILE: process.env.L2NODE_SHARED_CONFIG_FILE
            || path.join(rootDir, 'config', 'local.ini'),
        L2NODE_CONFIG_FILE: files.configPath,
        L2NODE_RUNTIME_DIR: files.runtimeDir,
        L2NODE_LAUNCHER_SETTINGS_FILE: files.launcherSettingsPath
    };

    if (noBrowser) environment.L2NODE_NO_BROWSER = '1';
    else delete environment.L2NODE_NO_BROWSER;

    return environment;
}

function isListening(port) {
    return new Promise((resolve) => {
        const socket = net.createConnection({ host: '127.0.0.1', port });
        const finish = (value) => {
            socket.destroy();
            resolve(value);
        };
        socket.once('connect', () => finish(true));
        socket.once('error', () => finish(false));
        socket.setTimeout(500, () => finish(false));
    });
}

function openBrowser(url) {
    if (process.env.L2NODE_NO_BROWSER === '1') return;

    const command = process.platform === 'win32'
        ? 'cmd.exe'
        : (process.platform === 'darwin' ? 'open' : 'xdg-open');
    const args = process.platform === 'win32' ? ['/c', 'start', '', url] : [url];
    const child = spawn(command, args, { detached: true, stdio: 'ignore', windowsHide: true });
    child.unref();
}

function requestJson(port, pathname, method = 'GET') {
    return new Promise((resolve, reject) => {
        const request = http.request({
            hostname: '127.0.0.1',
            port,
            path: pathname,
            method,
            headers: { 'Content-Type': 'application/json', 'Content-Length': method === 'GET' ? '0' : '2' }
        }, (response) => {
            let body = '';
            response.setEncoding('utf8');
            response.on('data', (chunk) => { body += chunk; });
            response.on('end', () => {
                if (response.statusCode < 200 || response.statusCode >= 300) {
                    reject(new Error(body || `HTTP ${response.statusCode}`));
                    return;
                }

                try {
                    resolve(body ? JSON.parse(body) : {});
                } catch (error) {
                    reject(new Error(`Invalid management response: ${error.message}`));
                }
            });
        });

        request.setTimeout(10000, () => request.destroy(new Error('Management request timed out.')));
        request.on('error', reject);
        request.end(method === 'GET' ? undefined : '{}');
    });
}

function wait(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms));
}

async function waitForManagement(definition, timeoutMs = 10000) {
    const deadline = Date.now() + timeoutMs;
    let lastError = null;

    while (Date.now() < deadline) {
        try {
            return await requestJson(definition.managementPort, '/observer/api/server/status');
        } catch (error) {
            lastError = error;
            await wait(100);
        }
    }

    throw lastError || new Error(`${definition.label} management did not become ready.`);
}

async function waitForPhase(definition, expectedPhase, timeoutMs) {
    const deadline = Date.now() + timeoutMs;
    let lastStatus = null;

    while (Date.now() < deadline) {
        try {
            lastStatus = await requestJson(definition.managementPort, '/observer/api/server/status');
            if (lastStatus.phase === expectedPhase) return lastStatus;
            if (lastStatus.phase === 'error') throw new Error(`${definition.label}: cleanup=${lastStatus.shutdownOutcome}, descendant exit=${lastStatus.treeConfirmed ? 'confirmed' : 'unknown'}`);
        } catch (error) {
            if (lastStatus?.phase === 'error') throw error;
            // Losing the management listener is not proof the game stopped.
        }
        await wait(250);
    }

    const detail = lastStatus?.logs?.slice(-3).map((entry) => entry.line).join(' | ');
    throw new Error(`${definition.label} did not reach ${expectedPhase}.${detail ? ` ${detail}` : ''}`);
}

async function launchInstance(definition, { noBrowser = false, baseDir = rootDir } = {}) {
    const files = ensureInstanceFiles(definition, baseDir);
    const url = managementUrl(definition);

    if (await isListening(definition.managementPort)) {
        if (!noBrowser) openBrowser(url);
        return { definition, files, url, reused: true, pid: null };
    }

    const child = spawn(process.execPath, [path.join('scripts', 'start.js')], {
        cwd: rootDir,
        env: environmentFor(definition, files, { noBrowser }),
        detached: true,
        stdio: 'ignore',
        windowsHide: true
    });
    child.unref();
    return { definition, files, url, reused: false, pid: child.pid };
}

async function startServer(definition, { noBrowser = false } = {}) {
    await launchInstance(definition, { noBrowser });
    const status = await waitForManagement(definition);
    if (status.phase === 'running') return status;
    if (status.phase === 'starting') return waitForPhase(definition, 'running', 120000);
    await requestJson(definition.managementPort, '/observer/api/server/start', 'POST');
    return waitForPhase(definition, 'running', 120000);
}

async function stopServer(definition) {
    if (!(await isListening(definition.managementPort))) {
        throw new Error(`${definition.label}: management unavailable; game shutdown cannot be confirmed.`);
    }

    const status = await waitForManagement(definition);
    if (status.phase === 'stopped') return status;
    if (status.phase !== 'stopping') {
        await requestJson(definition.managementPort, '/observer/api/server/stop', 'POST');
    }
    return waitForPhase(definition, 'stopped', 30000);
}

async function startServers(definitions, options) {
    const results = await Promise.all(definitions.map((definition) => startServer(definition, options)));
    results.forEach((status, index) => {
        console.log(`  ${definitions[index].label}: running (server pid ${status.pid || 'unknown'})`);
    });
}

async function stopServers(definitions) {
    const results = await Promise.all(definitions.map((definition) => stopServer(definition)));
    results.forEach((status, index) => {
        console.log(`  ${definitions[index].label}: stopped (cleanup ${status.shutdownOutcome || 'not started'})`);
    });
}

function selectedDefinitions(argv) {
    const countArgument = argv.find((value) => value.startsWith('--count='));
    const count = countArgument ? Number(countArgument.slice('--count='.length)) : 3;
    if (!Number.isInteger(count) || count < 1 || count > INSTANCE_DEFINITIONS.length) {
        throw new Error(`Use --count=1, --count=2, or --count=3.`);
    }
    return INSTANCE_DEFINITIONS.slice(0, count);
}

async function main() {
    const argv = process.argv.slice(2);
    const noBrowser = argv.includes('--no-browser');
    const definitions = selectedDefinitions(argv);
    const command = ['--start-servers', '--stop-servers', '--restart-servers']
        .filter((value) => argv.includes(value));

    if (command.length > 1) {
        throw new Error('Choose only one of --start-servers, --stop-servers, or --restart-servers.');
    }

    if (command[0] === '--stop-servers') {
        console.log('Stopping L2Node simulation servers:');
        await stopServers(definitions);
        return;
    }

    if (command[0] === '--restart-servers') {
        console.log('Restarting L2Node simulation servers:');
        await stopServers(definitions);
        await startServers(definitions, { noBrowser });
        return;
    }

    if (command[0] === '--start-servers') {
        console.log('Starting L2Node simulation servers:');
        await startServers(definitions, { noBrowser });
        return;
    }

    const results = [];

    for (const definition of definitions) {
        results.push(await launchInstance(definition, { noBrowser }));
    }

    console.log('L2Node simulations ready:');
    results.forEach(({ definition, files, url, reused, pid }) => {
        console.log(`  ${definition.label}: ${url} ${reused ? '(already running)' : `(management pid ${pid})`}`);
        console.log(`    database: ${files.databasePath}`);
        console.log(`    map:      http://127.0.0.1:${definition.managementPort}/observer/`);
    });
}

if (require.main === module) {
    main().catch((error) => {
        console.error(`Could not start simulations: ${error.stack || error}`);
        process.exitCode = 1;
    });
}

module.exports = {
    INSTANCE_DEFINITIONS,
    configText,
    ensureInstanceFiles,
    environmentFor,
    instanceFiles,
    managementUrl,
    selectedDefinitions
};
